#!/bin/sh
# install.sh — install free-ai-router on a machine without Nix.
#
# WHAT THIS IS FOR. On NixOS the module owns the binary, the configuration and
# the unit, and nothing here should touch that. Everywhere else there is no
# declaration to lean on, so this script builds the binary, puts it somewhere on
# PATH, writes the systemd user unit and says what to do next.
#
# WHAT IT DELIBERATELY DOES NOT DO:
#   - it does not touch /usr, or install a system-wide unit;
#   - it does not write into a Nix profile, and refuses to install over a binary
#     that Nix already owns (see below);
#   - it does not edit an existing config.json: settings belong to the operator,
#     and the CLI is the way to change them (`mode`, `cred`, `rotate`, `family`,
#     or a flag on any run).
#
# Usage:
#   ./install.sh                 build and install into ~/.local/bin
#   PREFIX=/opt/far ./install.sh install into another prefix (no sudo needed)
#   ./install.sh --unit          also write the systemd user unit
#   ./install.sh --no-build      install an existing ./free-ai-router binary
set -eu

prefix="${PREFIX:-$HOME/.local}"
bindir="$prefix/bin"

# The repository directory, without dirname(1): the script is meant to run on
# minimal systems, and a path expansion costs nothing.
case "$0" in
*/*) repo_dir=${0%/*} ;;
*) repo_dir=. ;;
esac
repo_dir=$(CDPATH= cd -- "$repo_dir" && pwd)

build=1
unit=0
for arg in "$@"; do
	case "$arg" in
	--no-build) build=0 ;;
	--unit) unit=1 ;;
	-h | --help)
		cat <<'EOF'
install.sh — build and install free-ai-router on a machine without Nix.

Usage:
  ./install.sh                 build and install into ~/.local/bin
  PREFIX=/opt/far ./install.sh install into another prefix (no sudo needed)
  ./install.sh --unit          also write the systemd user unit
  ./install.sh --no-build      install an existing ./free-ai-router binary

Settings are not touched: change them with the CLI (`mode`, `cred`, `rotate`,
`family`, or a flag on a single run).
EOF
		exit 0
		;;
	*)
		echo "install: unknown argument $arg" >&2
		exit 2
		;;
	esac
done

# A binary owned by Nix is not ours to replace. The check is on the RESOLVED
# path, because a profile binary is a symlink into the store: writing over the
# symlink target would either fail inside a read-only store or, with the link
# replaced, quietly detach the machine from its declaration.
if command -v free-ai-router >/dev/null 2>&1; then
	existing=$(command -v free-ai-router)
	resolved=$(readlink -f "$existing" 2>/dev/null || printf '%s' "$existing")
	case "$resolved" in
	/nix/store/*)
		echo "install: free-ai-router is already installed by Nix at $resolved" >&2
		echo "install: this script will not shadow it — use the NixOS module instead" >&2
		exit 1
		;;
	esac
fi

if [ "$build" -eq 1 ]; then
	command -v go >/dev/null 2>&1 || {
		echo "install: go is not on PATH; install Go, or pass --no-build with a prebuilt binary" >&2
		exit 1
	}
	echo "install: building in $repo_dir"
	# CGO off: the result is a static binary, which is what makes the unit and
	# the copy step trivial. A router does not need a C toolchain.
	(
		cd "$repo_dir"
		CGO_ENABLED=0 go build -trimpath -ldflags "-s -w" -o free-ai-router ./cmd/free-ai-router
	)
	bin="$repo_dir/free-ai-router"
else
	bin="$repo_dir/free-ai-router"
	[ -x "$bin" ] || {
		echo "install: no executable at $bin" >&2
		exit 1
	}
fi

mkdir -p "$bindir"
# install(1) is not on every minimal system, and a plain copy keeps the mode
# explicit.
cp "$bin" "$bindir/free-ai-router"
chmod 755 "$bindir/free-ai-router"
echo "install: $bindir/free-ai-router"

case ":$PATH:" in
*":$bindir:"*) ;;
*)
	echo "install: $bindir is not on PATH — add it to your shell profile:"
	echo "           export PATH=\"$bindir:\$PATH\""
	;;
esac

if [ "$unit" -eq 1 ]; then
	# The unit is generated by the binary so that it cannot drift from it.
	"$bindir/free-ai-router" systemd --install
fi

cat <<EOF

install: done. Next:
  free-ai-router axes                     every setting, its values, its default
  free-ai-router mode local               adopt a setting (kept in config.json)
  free-ai-router up --credential account  or try one for a single run
  free-ai-router tui                      watch it: keys, per-address matrix, log
EOF
