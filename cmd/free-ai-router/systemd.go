package main

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"free-ai-router/internal/config"
)

// THE UNIT BELONGS TO THE BINARY.
//
// On NixOS the unit is written by the module, and that is the end of it. Every
// other system needs the same unit, and the wrong way to give it one is a file
// in the repository: a copy on disk drifts from the binary it starts, and the
// drift is discovered on a machine where the daemon does not come up. So the
// text is generated here, from the same paths the daemon itself resolves, and it
// cannot disagree with the executable that prints it.

// systemdUnitPath is where a user unit lives.
func systemdUnitPath() (string, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return "", fmt.Errorf("systemd: no home directory: %w", err)
	}
	return filepath.Join(home, ".config", "systemd", "user", unitName), nil
}

const unitName = "free-ai-router.service"

// target reports where a symlink points, for the message.
func target(path string) string {
	if dest, err := os.Readlink(path); err == nil {
		return dest
	}
	return "unreadable"
}

// unitText renders the unit.
//
// The paths come from the running binary and the resolved configuration rather
// than from the environment of whoever runs the command: the unit is read by
// systemd, in a session where the operator's shell variables do not exist.
func unitText(exe string, cfg *config.Config) string {
	configHome := filepath.Dir(filepath.Dir(cfg.Paths.ConfigFile)) // .../<app>/config.json → .../..
	stateHome := filepath.Dir(filepath.Dir(cfg.Paths.StateFile))

	var b strings.Builder
	b.WriteString("# Generated by `free-ai-router systemd`. Edit the configuration and\n")
	b.WriteString("# regenerate, rather than editing this file: the next run overwrites it.\n")
	b.WriteString("\n[Unit]\n")
	b.WriteString("Description=free-ai-router — a gateway aggregating free AI providers\n")
	b.WriteString("Documentation=https://github.com/kyomufs/free-ai-router\n")
	// The gateway needs the network to reach the providers, and it must come up
	// after the network is usable rather than alongside it.
	b.WriteString("After=network-online.target\n")
	b.WriteString("Wants=network-online.target\n")
	b.WriteString("\n[Service]\n")
	// Type=simple with a foreground process: that is what `up` is without
	// --detach, and it is the shape systemd supervises correctly. A daemon that
	// forks hides its own crashes from the supervisor.
	b.WriteString("Type=simple\n")
	b.WriteString(fmt.Sprintf("ExecStart=%s up --config %s\n", exe, cfg.Paths.ConfigFile))
	b.WriteString("Restart=on-failure\n")
	b.WriteString("RestartSec=5\n")
	// The daemon's XDG roots. Without them a unit started outside a login
	// session reads a different config.json and writes a different state file —
	// the failure looks like "my settings are ignored".
	b.WriteString(fmt.Sprintf("Environment=XDG_CONFIG_HOME=%s\n", configHome))
	b.WriteString(fmt.Sprintf("Environment=XDG_STATE_HOME=%s\n", stateHome))
	// The token is NOT written here. In server mode the daemon reads
	// FREE_AI_ROUTER_TOKEN from the environment, and a token in this file would
	// be a secret in a plain file that anyone with a shell can read. The
	// commented line is the instruction, not a placeholder to fill in place.
	b.WriteString("# In server mode the token is required and must NOT be written here. Put it in\n")
	b.WriteString("# a file readable by you alone and uncomment:\n")
	b.WriteString("# EnvironmentFile=%h/.config/free-ai-router/token.env\n")
	b.WriteString("\n[Install]\n")
	// default.target, not multi-user.target: this is a user unit, and a user
	// session has no multi-user.target.
	b.WriteString("WantedBy=default.target\n")
	return b.String()
}

// cmdSystemd prints the user unit, or installs it.
//
// Printing and installing are two distinct acts: the first shows what would be
// written so it can be read before it is trusted, the second puts it where
// systemd looks. A single command that did both would make the first one
// impossible.
func cmdSystemd(args []string) error {
	install := false
	rest := make([]string, 0, len(args))
	for _, a := range args {
		switch a {
		case "--install":
			install = true
		case "-h", "--help":
			fmt.Fprint(os.Stderr, `free-ai-router systemd [--install]

  without --install: print the systemd user unit on stdout
  with --install:    write it to ~/.config/systemd/user/`+unitName+`

`+"`--install`"+` does not enable anything: it writes the file and prints the two
commands that do. Enabling a service is a decision about this machine's boot,
and it stays with its owner.
`)
			return nil
		default:
			// Everything else belongs to the ordinary flag set: --config decides
			// WHICH configuration the unit names, and it would be absurd for the
			// command that writes the unit to ignore it.
			rest = append(rest, a)
		}
	}

	cfg, _, err := loadConfig(rest)
	if err != nil {
		return err
	}
	if cfg == nil {
		return errors.New("systemd: no configuration")
	}

	exe, err := os.Executable()
	if err != nil {
		return fmt.Errorf("systemd: cannot locate this binary: %w", err)
	}
	// A relative or symlinked path in ExecStart breaks the unit the moment the
	// file moves, so the real path is resolved here, once.
	if resolved, err := filepath.EvalSymlinks(exe); err == nil {
		exe = resolved
	}

	text := unitText(exe, cfg)

	if !install {
		fmt.Print(text)
		return nil
	}

	path, err := systemdUnitPath()
	if err != nil {
		return err
	}
	// A SYMLINK MEANS SOMEBODY ELSE OWNS THIS FILE — a declarative system
	// (home-manager, ansible) put the unit here, and writing through the link
	// would either fail inside the store or, worse, fight the declaration on
	// every activation. That is a machine where the unit is managed elsewhere,
	// and the useful answer is to say so rather than to overwrite.
	if st, err := os.Lstat(path); err == nil && st.Mode()&os.ModeSymlink != 0 {
		return fmt.Errorf("systemd: %s is a symlink (%s): the unit is managed by something else on this machine, so it is not written here", path, target(path))
	}

	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("systemd: creating %s: %w", filepath.Dir(path), err)
	}
	if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
		return fmt.Errorf("systemd: writing %s: %w", path, err)
	}

	fmt.Printf("wrote %s\n", path)
	fmt.Println("now, to put it into service:")
	fmt.Println("  systemctl --user daemon-reload")
	fmt.Println("  systemctl --user enable --now free-ai-router")
	return nil
}
